// Cross-checks every CAUSES edge in the knowledge graph against current US product labels
// from openFDA (public, no key needed). Writes docs/LABEL_CHECK.md.
// Run on a machine with internet access:  npm run verify:labels
import { writeFileSync } from 'node:fs';
import { CAUSES, DRUG, EFFECT } from '../src/data/knowledge';
import { labelText, mentions } from '../src/lib/labels';

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const drugs = [...new Set(CAUSES.map(([d]) => d))];
const texts = new Map<string, string | null>();

async function fetchLabel(name: string): Promise<string | null> {
  const q = encodeURIComponent(`openfda.generic_name:"${name}"`);
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(`https://api.fda.gov/drug/label.json?search=${q}&limit=3`, { redirect: 'error' });
    if (res.status === 404) return null;
    if (res.status === 429) {
      await sleep(2000 * (attempt + 1));
      continue;
    }
    if (!res.ok) throw new Error(`openFDA ${res.status}`);
    const json = (await res.json()) as { results?: Record<string, unknown>[] };
    return (json.results ?? []).map(labelText).join(' ');
  }
  return null;
}

const ALIAS: Record<string, string> = {
  carbidopa_levodopa: 'carbidopa and levodopa',
  potassium_chloride: 'potassium chloride',
  polyethylene_glycol: 'polyethylene glycol 3350',
  insulin_glargine: 'insulin glargine',
  calcium_vitd: 'calcium carbonate',
  ferrous_sulfate: 'ferrous sulfate',
  aspirin: 'aspirin',
};

for (const d of drugs) {
  const name = ALIAS[d] ?? DRUG[d]!.name.toLowerCase();
  try {
    texts.set(d, await fetchLabel(name));
  } catch (e) {
    console.error(`  ${d}: ${(e as Error).message}`);
    texts.set(d, null);
  }
  process.stdout.write(`\r  fetched ${texts.size}/${drugs.length} labels`);
  await sleep(300);
}
console.log('');

let found = 0;
let missing = 0;
let noLabel = 0;
const rows: string[] = [];
for (const [d, e, freq] of CAUSES) {
  const text = texts.get(d);
  if (!text) {
    noLabel++;
    rows.push(`| ${DRUG[d]!.name} | ${EFFECT[e]!.name} | ${freq} | no US label found |`);
    continue;
  }
  const term = mentions(text, e);
  if (term) found++;
  else missing++;
  rows.push(`| ${DRUG[d]!.name} | ${EFFECT[e]!.name} | ${freq} | ${term ? `✓ "${term}"` : '✗ not found in label text'} |`);
}
const checked = found + missing;
const md = `# Knowledge graph vs FDA labels

Generated by \`npm run verify:labels\` on ${new Date().toISOString().slice(0, 10)} from openFDA drug labels
(adverse reactions, warnings and precautions sections). A keyword match is a sanity check, not proof: labels list many effects,
and some of ours are class effects described in other words.

**${found} of ${checked} CAUSES edges (${checked ? Math.round((found / checked) * 100) : 0}%) are mentioned in the drug's US label.** ${noLabel} edges belong to drugs without a US label
(for example betahistine and zopiclone, which are not marketed in the US).

| Drug | Effect | Frequency band | Label |
| - | - | - | - |
${rows.join('\n')}
`;
writeFileSync('docs/LABEL_CHECK.md', md);
console.log(`  ${found}/${checked} edges confirmed in label text, ${noLabel} without a US label → docs/LABEL_CHECK.md`);
