/**
 * Lookup by id. Null-prototype objects, so an id like "constructor" or "__proto__" from a request
 * never resolves to an inherited property (OWASP A05, prototype pollution and confusion).
 */
export function lookup<T extends { id: string }>(items: readonly T[]): Readonly<Record<string, T | undefined>> {
  const map = Object.create(null) as Record<string, T | undefined>;
  for (const item of items) map[item.id] = item;
  return Object.freeze(map);
}

