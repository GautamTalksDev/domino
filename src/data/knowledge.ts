// Domino's medication knowledge graph, curated by hand from product labelling,
// the AGS Beers Criteria (2023), the Anticholinergic Cognitive Burden scale and
// the prescribing cascade literature (see references.ts).
//
// This is a prototype knowledge base for a hackathon. Frequencies are coarse bands
// and onset windows are typical ranges, not exact values. It is not a clinical
// reference and must not be used to make treatment decisions.

export type Freq = 'very_common' | 'common' | 'uncommon' | 'rare';
export type EffectKind = 'symptom' | 'condition' | 'lab' | 'harm';
export type Evidence = 'consensus' | 'study' | 'label';

export const FREQ_WEIGHT: Record<Freq, number> = {
  very_common: 0.9,
  common: 0.7,
  uncommon: 0.4,
  rare: 0.2,
};

export const FREQ_LABEL: Record<Freq, string> = {
  very_common: 'very common (more than 1 in 10)',
  common: 'common (1 to 10 in 100)',
  uncommon: 'uncommon (1 to 10 in 1,000)',
  rare: 'rare',
};

export interface ClassDef {
  id: string;
  name: string;
  /** Deprescribing safety: why a change in this class needs a gradual taper or specialist input. */
  taper?: string;
}

export interface DrugDef {
  id: string;
  name: string;
  cls: string;
  acb?: 1 | 2 | 3; // Anticholinergic Cognitive Burden score (approximate)
  beers?: string; // AGS Beers 2023 note, when listed
}

export interface EffectDef {
  id: string;
  name: string;
  plain: string;
  kind: EffectKind;
}

// [drug, effect, frequency, onset window in days [min, max]]
export type CauseDef = [string, string, Freq, [number, number]?];
// [effect, drug, line]
export type TreatDef = [string, string, ('first' | 'second' | 'off_label')?];
// [from effect, to effect, weight]
export type RaiseDef = [string, string, number];

export interface PatternDef {
  id: string;
  title: string;
  index: string[]; // index drug classes
  effect: string;
  marker: string[]; // marker drug classes
  evidence: Evidence;
  refs: string[];
  intentional?: string; // set when the pair is often deliberate (e.g. gastroprotection)
  realWorld?: { asr: number; lo: number; hi: number; prevalence: number; note: string };
  realWorldNegative?: string;
  question: string; // the question Domino suggests a pharmacist asks
}

export interface ComboDef {
  id: string;
  title: string;
  harm: string;
  groups: string[][]; // one drug class from every group must be present
  refs: string[];
  why: string;
}

